"""Rendering baresip's accounts/config from the VOIP_* settings."""

import stat

import pytest

from payphone.config.settings import Config
from payphone.voip import account as account_module
from payphone.voip.account import (
    VoipAccount,
    main,
    normalize_sip_uri,
    render_accounts,
    render_config,
    write_baresip_config,
)


def account_line(text: str) -> str:
    return [line for line in text.splitlines() if line and not line.startswith("#")][0]


@pytest.mark.parametrize(
    "raw, expected",
    [
        ("sip:463@10.0.0.1", "sip:463@10.0.0.1"),
        ("463@10.0.0.1", "sip:463@10.0.0.1"),
        ("SIP:463@hub.local:5060", "sip:463@hub.local:5060"),
        ("sips:463@hub.local", "sips:463@hub.local"),
        ("  sip:463@10.0.0.1;transport=tcp ", "sip:463@10.0.0.1;transport=tcp"),
    ],
)
def test_normalize_sip_uri(raw, expected):
    assert normalize_sip_uri(raw) == expected


@pytest.mark.parametrize("raw", ["", "   ", "tel:+15551234", "sip:10.0.0.1", "sip:463@", "sip:4 63@h", "<sip:1@h>"])
def test_normalize_sip_uri_rejects_bad_aors(raw):
    with pytest.raises(ValueError):
        normalize_sip_uri(raw)


def test_registrar_may_omit_user_and_scheme():
    assert normalize_sip_uri("10.0.0.1", require_user=False) == "sip:10.0.0.1"
    assert normalize_sip_uri("10.0.0.1:5060", require_user=False) == "sip:10.0.0.1:5060"


def test_render_accounts_basic_line():
    text = render_accounts(VoipAccount("sip:463@10.0.0.1", password="s3cret"))
    assert text.startswith("# Generated by payphone.voip.account")
    assert account_line(text) == "<sip:463@10.0.0.1>;auth_pass=s3cret;regint=600"


def test_registrar_on_the_aor_host_needs_no_outbound_proxy():
    for registrar in ("", "10.0.0.1", "sip:10.0.0.1"):
        line = account_line(render_accounts(VoipAccount("463@10.0.0.1", registrar, "pw")))
        assert "outbound" not in line


def test_different_registrar_becomes_the_outbound_proxy():
    line = account_line(render_accounts(VoipAccount("sip:463@burningman.local", "10.0.0.1", "pw")))
    assert line == '<sip:463@burningman.local>;auth_pass=pw;outbound="sip:10.0.0.1";regint=600'


def test_account_without_password_omits_auth_pass():
    assert account_line(render_accounts(VoipAccount("sip:463@10.0.0.1"))) == "<sip:463@10.0.0.1>;regint=600"


@pytest.mark.parametrize("password", ["a;b", 'a"b', "a b", "a<b", "a,b"])
def test_password_that_breaks_baresip_parsing_is_rejected(password):
    with pytest.raises(ValueError, match="VOIP_PASSWORD"):
        render_accounts(VoipAccount("sip:463@10.0.0.1", password=password))


def test_render_config_is_headless_and_loopback_only():
    text = render_config()
    settings = {}
    modules = []
    for line in text.splitlines():
        if not line or line.startswith("#"):
            continue
        key, value = line.split(None, 1)
        if key in ("module", "module_app"):
            modules.append(value)
        else:
            settings[key] = value

    assert settings["ctrl_tcp_listen"] == "127.0.0.1:4444"
    assert settings["audio_player"] == settings["audio_source"] == "alsa,default"
    for required in ("ctrl_tcp.so", "menu.so", "account.so", "mwi.so", "alsa.so", "g711.so"):
        assert required in modules
    assert "stdio.so" not in modules
    assert "module_path" not in settings


def test_render_config_options():
    text = render_config(ctrl_port=5555, audio_device="plughw:1,0", module_path="/usr/lib/baresip/modules")
    assert "127.0.0.1:5555" in text
    assert "alsa,plughw:1,0" in text
    assert "/usr/lib/baresip/modules" in text


def test_write_baresip_config_keeps_password_private(tmp_path):
    paths = write_baresip_config(tmp_path / "baresip", VoipAccount("sip:463@10.0.0.1", password="pw"))

    accounts, config = paths
    assert accounts.name == "accounts" and config.name == "config"
    assert stat.S_IMODE(accounts.stat().st_mode) == 0o600
    assert "auth_pass=pw" in accounts.read_text()
    assert "ctrl_tcp_listen" in config.read_text()


@pytest.fixture
def voip_settings(monkeypatch, tmp_path):
    values = {
        "VOIP_ENABLED": True,
        "VOIP_SIP_URI": "sip:463@10.0.0.1",
        "VOIP_REGISTRAR": "",
        "VOIP_PASSWORD": "pw",
        "VOIP_CONFIG_DIR": str(tmp_path / "rendered"),
    }
    for key, value in values.items():
        monkeypatch.setattr(Config, key, value)
    return tmp_path / "rendered"


def test_cli_renders_into_voip_config_dir(voip_settings):
    assert main([]) == 0
    assert (voip_settings / "accounts").exists()
    assert (voip_settings / "config").exists()


def test_cli_does_nothing_when_voip_disabled(voip_settings, monkeypatch):
    monkeypatch.setattr(Config, "VOIP_ENABLED", False)
    assert main([]) == 0
    assert not voip_settings.exists()


def test_cli_fails_on_invalid_settings(voip_settings, monkeypatch):
    monkeypatch.setattr(Config, "VOIP_SIP_URI", "")
    assert main([]) == 1
    assert not voip_settings.exists()


def test_cli_print_masks_password(voip_settings, capsys):
    assert main(["--print"]) == 0
    out = capsys.readouterr().out
    assert "auth_pass=****" in out and "auth_pass=pw" not in out
    assert not voip_settings.exists()


def test_settings_expose_voip_keys():
    for key in ("VOIP_ENABLED", "VOIP_SIP_URI", "VOIP_REGISTRAR", "VOIP_PASSWORD", "VOIP_CONFIG_DIR"):
        assert hasattr(Config, key)
    assert account_module.DEFAULT_PORT == 4444
