"""
Render baresip's ``accounts`` and ``config`` files from payphone settings.

The ``VOIP_*`` keys in ``.env`` (or /etc/payphone/.env on the Pi, written by
scripts/inject_secrets.sh) describe one SIP account:

    VOIP_ENABLED=true
    VOIP_SIP_URI=sip:463@10.0.0.1
    VOIP_REGISTRAR=            # optional; defaults to the URI's host
    VOIP_PASSWORD=...

Run ``python3 -m payphone.voip.account`` to write ``<VOIP_CONFIG_DIR>/accounts``
and ``<VOIP_CONFIG_DIR>/config``; baresip.service does this before every start
(``ExecStartPre``) so the files always match the current environment.
"""

import argparse
import logging
import os
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import List, Optional, Sequence

from .baresip import DEFAULT_HOST, DEFAULT_PORT

logger = logging.getLogger(__name__)

#: Characters that would break baresip's ``;key=value`` account parameters.
_UNSAFE_PASSWORD_CHARS = frozenset(' \t\r\n;"<>,')

HEADER = "# Generated by payphone.voip.account from the VOIP_* settings. Do not edit:\n" \
         "# this file is rewritten every time baresip.service starts.\n"


@dataclass(frozen=True)
class VoipAccount:
    """One SIP account: address of record, registrar and password."""

    sip_uri: str
    registrar: str = ""
    password: str = ""

    @classmethod
    def from_config(cls, config) -> "VoipAccount":
        """Build from a :class:`payphone.config.settings.Config`-like object."""
        return cls(
            sip_uri=getattr(config, "VOIP_SIP_URI", "") or "",
            registrar=getattr(config, "VOIP_REGISTRAR", "") or "",
            password=getattr(config, "VOIP_PASSWORD", "") or "",
        )

    @property
    def aor(self) -> str:
        """The SIP URI with a ``sip:`` scheme, e.g. ``sip:463@10.0.0.1``."""
        return normalize_sip_uri(self.sip_uri)

    @property
    def host(self) -> str:
        """Host (and optional port) part of the address of record."""
        return self.aor.split(":", 1)[1].split("@", 1)[1].split(";", 1)[0]

    @property
    def outbound(self) -> str:
        """Registrar URI when it differs from the AOR host, else empty.

        baresip registers with the host in the AOR; a different registrar is
        configured as the account's outbound proxy.
        """
        if not self.registrar.strip():
            return ""
        registrar = normalize_sip_uri(self.registrar, require_user=False)
        if registrar.split(":", 1)[1] == self.host:
            return ""
        return registrar

    def validate(self) -> None:
        """Raise ValueError if the account cannot be rendered safely."""
        normalize_sip_uri(self.sip_uri)
        if self.registrar.strip():
            normalize_sip_uri(self.registrar, require_user=False)
        bad = sorted(set(self.password) & _UNSAFE_PASSWORD_CHARS)
        if bad:
            raise ValueError(f"VOIP_PASSWORD contains characters baresip cannot parse: {bad!r}")


def normalize_sip_uri(uri: str, *, require_user: bool = True) -> str:
    """Return ``uri`` with a ``sip:`` scheme, validating its basic shape.

    Args:
        uri: ``sip:463@10.0.0.1``, ``463@10.0.0.1`` or (registrar) ``10.0.0.1``.
        require_user: Require a ``user@host`` part (true for an AOR).

    Raises:
        ValueError: for empty input, whitespace, a non-SIP scheme or a missing
            user/host.
    """
    uri = (uri or "").strip()
    if not uri:
        raise ValueError("SIP URI is empty (set VOIP_SIP_URI)")
    if any(ch.isspace() for ch in uri) or any(ch in uri for ch in '<>"'):
        raise ValueError(f"SIP URI contains invalid characters: {uri!r}")
    scheme, sep, rest = uri.partition(":")
    if sep and scheme.lower() in ("sip", "sips"):
        uri = f"{scheme.lower()}:{rest}"
    elif "@" in uri or not sep or rest.isdigit():
        # No scheme ("463@host", "host", "host:5060").
        uri, rest = f"sip:{uri}", uri
    else:
        raise ValueError(f"Not a SIP URI: {uri!r}")
    user, at, host = rest.rpartition("@")
    if require_user and not (at and user):
        raise ValueError(f"SIP URI needs user@host: {uri!r}")
    if not host.split(";", 1)[0]:
        raise ValueError(f"SIP URI has no host: {uri!r}")
    return uri


def render_accounts(account: VoipAccount, *, regint: int = 600) -> str:
    """Render baresip's ``accounts`` file for ``account``.

    Example line::

        <sip:463@10.0.0.1>;auth_pass=secret;regint=600
    """
    account.validate()
    params = []
    if account.password:
        params.append(f"auth_pass={account.password}")
    if account.outbound:
        params.append(f'outbound="{account.outbound}"')
    params.append(f"regint={int(regint)}")
    return HEADER + f"<{account.aor}>;" + ";".join(params) + "\n"


def render_config(
    *,
    ctrl_host: str = DEFAULT_HOST,
    ctrl_port: int = DEFAULT_PORT,
    sip_listen: str = "0.0.0.0:5060",
    audio_device: str = "default",
    module_path: Optional[str] = None,
) -> str:
    """Render a minimal headless baresip ``config``.

    - ALSA ``default`` device for playback, capture and ringing. With the
      dmix/dsnoop ``/etc/asound.conf`` from scripts/setup_pi.sh, pygame and
      baresip can open the card at the same time.
    - ctrl_tcp bound to loopback only: anyone who can reach it can place
      calls, so it must not listen on the playa LAN.
    - No ``stdio`` UI module; payphone is the only controller.
    """
    lines = [HEADER.rstrip("\n"), ""]

    def kv(key: str, value: str) -> None:
        lines.append(f"{key:<24}{value}")

    if module_path:
        kv("module_path", module_path)
    kv("sip_listen", sip_listen)
    kv("audio_player", f"alsa,{audio_device}")
    kv("audio_source", f"alsa,{audio_device}")
    kv("audio_alert", f"alsa,{audio_device}")
    kv("ctrl_tcp_listen", f"{ctrl_host}:{ctrl_port}")
    lines.append("")
    lines.append("# Codecs and audio drivers")
    for module in ("g711.so", "alsa.so", "auconv.so", "auresamp.so"):
        kv("module", module)
    lines.append("")
    lines.append("# Application modules: accounts file, commands, control socket, voicemail")
    for module in ("account.so", "menu.so", "ctrl_tcp.so", "mwi.so"):
        kv("module_app", module)
    return "\n".join(lines) + "\n"


def write_baresip_config(config_dir: os.PathLike, account: VoipAccount, **config_kwargs) -> List[Path]:
    """Write ``accounts`` (mode 600, it holds the password) and ``config``.

    Returns:
        The written paths.
    """
    directory = Path(config_dir)
    directory.mkdir(parents=True, exist_ok=True)
    accounts_path = directory / "accounts"
    config_path = directory / "config"

    accounts_text = render_accounts(account)
    # Create with 0600 so the password is never world-readable, even briefly.
    fd = os.open(accounts_path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as handle:
        handle.write(accounts_text)
    os.chmod(accounts_path, 0o600)

    config_path.write_text(render_config(**config_kwargs))
    return [accounts_path, config_path]


def main(argv: Optional[Sequence[str]] = None) -> int:
    """CLI: render baresip config from the VOIP_* settings."""
    from ..config.settings import Config

    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0].strip())
    parser.add_argument("--config-dir", default=None, help="Output directory (default: VOIP_CONFIG_DIR)")
    parser.add_argument("--print", action="store_true", help="Print config to stdout, password masked; write nothing")
    args = parser.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(message)s")

    config = Config()
    if not config.VOIP_ENABLED:
        logger.info("VOIP_ENABLED is not true; nothing to render")
        return 0

    account = VoipAccount.from_config(config)
    try:
        account.validate()
    except ValueError as exc:
        logger.error("Invalid VoIP settings: %s", exc)
        return 1

    if args.print:
        masked = VoipAccount(account.sip_uri, account.registrar, "****" if account.password else "")
        sys.stdout.write(render_accounts(masked) + "\n" + render_config())
        return 0

    config_dir = args.config_dir or config.VOIP_CONFIG_DIR
    for path in write_baresip_config(config_dir, account):
        logger.info("Wrote %s", path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
